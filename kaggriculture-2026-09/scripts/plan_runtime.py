# ---- runtime liveness self-check -------------------------------------------
# Three times now a generated agent has been measured while inert or frozen (the
# mode-dispatch ordering bug raised on every step and the harness fallback left the
# agent sitting on its starting money, producing a plausible-looking, parameter- and
# behaviour-independent curve).  A generated agent must be impossible to measure by
# accident, so it audits itself and shouts.
_LIVE = {{"money0": None, "steps": 0, "farmer_ops": 0, "noop_units": 0, "units": 0,
         "mkt_ops": 0, "violations": []}}


def _audit(observation, act, unit_noop):
    s = int(observation["step"])
    if _LIVE["money0"] is None:
        _LIVE["money0"] = float(observation["farms"][int(observation["player"])]["money"])
    _LIVE["steps"] += 1
    fr = act.get("farmer") or ["PASS"]
    if fr and fr[0] != "PASS":
        _LIVE["farmer_ops"] += 1
    _LIVE["units"] += 1 + len(act.get("hands") or [])
    _LIVE["noop_units"] += int(unit_noop)
    _LIVE["mkt_ops"] += len(act.get("market") or [])
    if s >= 719:
        money = float(observation["farms"][int(observation["player"])]["money"])
        if money == _LIVE["money0"]:
            _LIVE["violations"].append("FROZEN: money unchanged from start")
        if _LIVE["farmer_ops"] == 0:
            _LIVE["violations"].append("INERT: no farmer op ever issued")
        if _LIVE["mkt_ops"] == 0:
            _LIVE["violations"].append("INERT: no market op ever issued")
        rate = _LIVE["noop_units"] / max(1, _LIVE["units"])
        if rate > 0.9:
            _LIVE["violations"].append(f"INERT: {{100*rate:.0f}}% of unit actions were no-ops")
        print("LIVENESS", _json.dumps({{k: _LIVE[k] for k in
              ("steps", "money0", "farmer_ops", "units", "noop_units", "mkt_ops")}}),
              "violations", _LIVE["violations"], flush=True)
        mean_steps = (_SCHED["steps"] / max(1, _SCHED["started"])) if "_SCHED" in globals() else 0
        print("SCHEDULER", _json.dumps(dict(_SCHED, mean_steps_per_assignment=round(mean_steps, 1))),
              flush=True)
        if _LIVE["violations"]:
            raise RuntimeError("generated agent failed its liveness audit: "
                               + "; ".join(_LIVE["violations"]))

