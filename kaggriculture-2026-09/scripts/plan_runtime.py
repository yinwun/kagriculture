def build(theta_path, mode, trace_dir, out):
    theta = json.loads(Path(theta_path).read_text())
    units = {}
    if mode == "hybrid" and trace_dir:
        for line in Path(trace_dir, "trace.jsonl").read_text().splitlines():
            r = json.loads(line)
            units[str(r["step"])] = {"farmer": r["action"]["farmer"],
                                     "hands": r["action"]["hands"]}
    src = TEMPLATE.format(mode=mode, theta_path=str(theta_path),
                          theta_json=json.dumps(theta), units_json=json.dumps(units))
    compile(src, str(out), "exec")
    Path(out).write_text(src)
    print(f"wrote {out} (mode={mode}, θ fields "
          f"{sum(1 for k in theta if k not in ('source','seed','recovery'))})")
    return out


