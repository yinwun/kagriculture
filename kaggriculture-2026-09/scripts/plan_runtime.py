"""S1.2 controller: turn θ (`data/plan/theta*.json`) into actions.

Two modes, because they answer different questions:

  --mode theta    everything comes from θ: a priority unit policy (act on the tile you
                  stand on when it needs work, otherwise walk to the nearest tile that
                  does) plus the θ market schedule.  This is the S1 target agent.
  --mode hybrid   the MARKET comes from θ and the unit actions come from the reference
                  trace of the same seed.  A diagnostic: it separates "can θ carry the
                  market" from "can θ carry the routing", which the S1 residual table
                  needs, and it is cheap.

θ market semantics: `sell["<day>|<item>"]` is the list of lots the plan wants sold that
day; the controller offers them at the day's first `len(lots)` hours (one lot per hour,
merged into one order per item per hour), gated by `price_gate[item]` (do not sell below
the lowest price the reference ever accepted).  `buy_feed["<day>|<item>"]`,
`buy_animal[day]`, `hire[day]` are issued at the day's first hour.

Usage:
  .venv/bin/python scripts/plan_runtime.py --theta data/plan/theta-9000.json \
      --mode hybrid --trace data/trace/wool_drain1_outerprem-9000 --out data/plan/agent-hybrid-9000.py
"""
